function text(key, values = {}) {
  return translations[activeLanguage][key].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

function updateThemeLabel() {
  const isDark = document.body.classList.contains("dark-theme");
  themeButton.setAttribute("aria-pressed", String(isDark));
  themeButton.setAttribute("aria-label", text(isDark ? "theme.light" : "theme.dark"));
  themeLabel.textContent = text("theme.label");
  themeColorMeta.setAttribute("content", isDark ? "#101812" : "#f5f7f2");
}

function updateCheckProgress() {
  const completed = [...installChecks].filter((item) => item.checked).length;
  checkProgress.textContent = text("install.check.progress", { count: completed });
}

function updateGameStatus() {
  const statusKey = gameState === "playing" ? "game.playing" : gameState === "finished" ? "game.finished" : "game.ready";
  gameStatus.textContent = text(statusKey, { score });
}

function updateFlappyStatus() {
  const key = flappyState === "playing" ? "flappy.playing" : flappyState === "over" ? "flappy.over" : "flappy.ready";
  flappyStatus.textContent = text(key, { score: flappyScore });
}

function updateDriveStatus() {
  const key = driveState === "playing" ? "drive.playing" : driveState === "over" ? "drive.over" : "drive.ready";
  driveStatus.textContent = text(key, { score: driveScore });
}

function setLanguage(language) {
  activeLanguage = translations[language] ? language : "uk";
  document.documentElement.lang = activeLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = text(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = text(element.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", text(element.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    element.setAttribute("content", text(element.dataset.i18nContent));
  });
  document.title = text("meta.title");
  languageSelect.value = activeLanguage;
  updateThemeLabel();
  updateCheckProgress();
  updateGameStatus();
  updateFlappyStatus();
  flappyStartButton.textContent = text(flappyState === "over" ? "flappy.restart" : "flappy.start");
  updateDriveStatus();
  driveStartButton.textContent = text(driveState === "over" ? "drive.restart" : "drive.start");
}

